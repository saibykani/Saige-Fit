"""Generate supabase/migrations/0006_seed_exercises_recipes.sql from the Python seed data.
Refuses to write if the data is inconsistent (unknown alternatives / recipe ingredients, bad counts).

Usage: python -m scripts.gen_seed_training
"""
from pathlib import Path

from app.data.curated_foods import FOODS
from app.data.exercises_seed import EXERCISES
from app.data.recipes_seed import R

OUT = Path(__file__).resolve().parents[2] / "supabase" / "migrations" / "0006_seed_exercises_recipes.sql"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def arr(items: list[str]) -> str:
    return "array[" + ",".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def check() -> None:
    names = {e["name"] for e in EXERCISES}
    assert len(names) == len(EXERCISES), "duplicate exercise names"
    for e in EXERCISES:
        bad = [a for a in e["alternatives"] if a not in names]
        assert not bad, f"{e['name']}: unknown alternatives {bad}"
    foods = {f[0] for f in FOODS}
    for r in R:
        bad = [i[0] for i in r[8] if i[0] not in foods]
        assert not bad, f"{r[0]}: unknown foods {bad}"


def main() -> None:
    check()
    out = ["-- GENERATED by backend/scripts/gen_seed_training.py. Do not edit by hand."]
    for e in EXERCISES:
        out.append(
            "insert into exercises(name,muscle_group,secondary_muscles,equipment,difficulty,instructions,common_mistakes,"
            "contraindications,is_compound) values ("
            f"{q(e['name'])},{q(e['muscle_group'])},{arr(e['secondary_muscles'])},{arr(e['equipment'])},"
            f"{q(e['difficulty'])}::experience_t,{arr(e['instructions'])},{arr(e['common_mistakes'])},"
            f"{arr(e['contraindications'])},{'true' if e['is_compound'] else 'false'});"
        )
    for e in EXERCISES:
        if e["alternatives"]:
            out.append(
                "update exercises set alternative_ids = coalesce((select array_agg(a.id) from exercises a "
                f"where a.name = any({arr(e['alternatives'])})), '{{}}') where name = {q(e['name'])};"
            )
    for name, cuisine, desc, servings, prep, cook, tags, steps, ingredients in R:
        out.append(
            "insert into recipes(name,cuisine,description,servings,prep_minutes,cook_minutes,tags,steps) values ("
            f"{q(name)},{q(cuisine)},{q(desc)},{servings},{prep},{cook},{arr(tags)},{arr(steps)});"
        )
        for pos, (food, grams, note) in enumerate(ingredients):
            out.append(
                "insert into recipe_ingredients(recipe_id,food_id,grams,note,position) select r.id, f.id, "
                f"{grams}, {q(note) if note else 'null'}, {pos} from recipes r, food_items f "
                f"where r.name = {q(name)} and f.name = {q(food)} and f.owner_id is null;"
            )
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(EXERCISES)} exercises, {len(R)} recipes -> {OUT}")


if __name__ == "__main__":
    main()
