"""Generate supabase/migrations/0003_seed_foods.sql from app/data/curated_foods.py.
Refuses to write if any record fails nutrition validation.

Usage: python -m scripts.gen_seed
"""
from pathlib import Path

from app.data.curated_foods import DIET_TAGS, FOODS
from app.services.nutrition_engine import Nutrients, validate_per_100g

OUT = Path(__file__).resolve().parents[2] / "supabase" / "migrations" / "0003_seed_foods.sql"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def arr(items: list[str], cast: str) -> str:
    return "array[" + ",".join(q(i) for i in items) + f"]::{cast}[]" if items else f"'{{}}'::{cast}[]"


def main() -> None:
    lines = ["-- GENERATED by backend/scripts/gen_seed.py. Do not edit by hand."]
    for (name, cuisine, diet, allergens, kcal, p, c, f, sat, fib, sug, na, serv, label, unit) in FOODS:
        n = Nutrients(kcal, p, c, f, sat, fib, sug, na)
        problems = validate_per_100g(n)
        if problems:
            raise SystemExit(f"{name}: {problems}")
        lines.append(
            "with f as (insert into food_items(name,source,cuisine,diet_tags,allergens,default_serving_g,serving_label,grams_per_unit) "
            f"values ({q(name)},'curated',{q(cuisine)},{arr(DIET_TAGS[diet], 'diet_t')},{arr(allergens, 'text')},{serv},{q(label)},{unit}) returning id) "
            "insert into food_nutrition(food_id,kcal,protein_g,carbs_g,fat_g,sat_fat_g,fiber_g,sugar_g,sodium_mg) "
            f"select id,{kcal},{p},{c},{f},{sat},{fib},{sug},{na} from f;"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(FOODS)} foods -> {OUT}")


if __name__ == "__main__":
    main()
